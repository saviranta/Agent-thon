#!/usr/bin/env python3
"""sync-instructions.py — generate AI-coder instruction files from one source.

Usage: sync-instructions.py <project-root> [--check]

Sources: .agentthon/config.json (project, team, checks), .agentthon/ownership.yml, TEAM.md,
.agentthon/artifacts/brief.md (Purpose section), .agentthon/artifacts/conventions.md, contracts/.
Outputs (identical rules, tool-specific headers):
  AGENTS.md                         — Codex and other AGENTS.md-aware tools
  .github/copilot-instructions.md   — GitHub Copilot
  CLAUDE.md                         — Claude Code sessions outside Agent-thon
--check: exit 1 if any output is missing or out of date (CI).
"""

import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ownership import load_ownership  # noqa: E402

MARK = "<!-- Generated by Agent-thon (sync-instructions.py). Do not edit by hand — change the sources and regenerate. -->"
OUTPUTS = {
    "AGENTS.md": "# Instructions for AI coding agents",
    os.path.join(".github", "copilot-instructions.md"): "# Copilot instructions",
    "CLAUDE.md": "# Project instructions for Claude Code",
}
MAX_CONVENTIONS_CHARS = 6000


def read(root, rel):
    p = os.path.join(root, rel)
    return open(p).read() if os.path.exists(p) else ""


def section(md, title):
    m = re.search(rf"^##\s+{re.escape(title)}\s*$(.*?)(?=^##\s|\Z)", md, re.M | re.S)
    return m.group(1).strip() if m else ""


def body(root):
    cfg = json.load(open(os.path.join(root, ".agentthon", "config.json")))
    areas = load_ownership(root)
    brief = read(root, ".agentthon/artifacts/brief.md")
    conventions = read(root, ".agentthon/artifacts/conventions.md").strip()
    purpose = section(brief, "Purpose") or cfg.get("project_description") or "(brief not written yet)"

    out = [f"Project: **{cfg.get('project_name')}** — {purpose.splitlines()[0] if purpose else ''}", ""]

    out += ["## Before you change anything", "",
            "1. Check `.agentthon/ownership.yml` (summary below). Only change paths you own or have agreed with the owner.",
            "2. Check `.agentthon/claims.md` — don't work inside someone else's claimed path.",
            "3. Work on a branch `<your-name>/<topic>` and open a PR to `main`. Never commit to `main`.",
            "4. Contracts in `contracts/` change only via the Architect (open a GitHub issue labelled `architect` or add to `.agentthon/requests.md`).",
            "5. Dependencies: exact versions only — never `^`, `~` or ranges. Declare dependency changes in the PR.",
            "6. Never commit secrets or `.env` files; use `.env.example` for variable names.",
            "7. Don't edit generated files: `AGENTS.md`, `CLAUDE.md`, `.github/copilot-instructions.md`, `.github/CODEOWNERS`.",
            "8. Don't touch `.agentthon/` (planning and agent state) unless you are working with the Architect.", ""]

    def owners(kind):
        return [a["path"] for a in areas if a["owner"] == kind]
    people = {}
    for a in areas:
        if a["owner"] and a["owner"].startswith("@"):
            people.setdefault(a["owner"], []).append(a["path"])
    out += ["## Ownership summary", ""]
    for who, paths in sorted(people.items()):
        out.append(f"- **{who}**: " + ", ".join(f"`{p}`" for p in paths))
    if owners("agents"):
        out.append("- **agents** (built by Agent-thon; coordinate with the Architect before changing): " + ", ".join(f"`{p}`" for p in owners("agents")))
    if owners("shared"):
        out.append("- **shared** (announce first, small dedicated PR): " + ", ".join(f"`{p}`" for p in owners("shared")))
    if owners("architect"):
        out.append("- **architect** (change via the Architect only): " + ", ".join(f"`{p}`" for p in owners("architect")))
    out.append("")

    checks = cfg.get("checks", {})
    cmds = [(k, c) for k in ("setup", "lint", "types", "unit", "contract", "e2e") for c in (checks.get(k) or [])]
    out += ["## Checks (CI runs these on every PR)", ""]
    if cmds:
        out += [f"- {k}: `{c}`" for k, c in cmds]
    else:
        out.append("- Not configured yet (the Architect fills `.agentthon/config.json` → `checks`).")
    out += ["- ownership: `python3 .agentthon/bin/ownership-check.py pr . origin/main <your-branch>`",
            "- versions: `python3 .agentthon/bin/check-versions.py .`", ""]

    contract_files = []
    cdir = os.path.join(root, "contracts")
    if os.path.isdir(cdir):
        for d, _, files in os.walk(cdir):
            contract_files += [os.path.relpath(os.path.join(d, f), root) for f in sorted(files)]
    out += ["## Contracts (read-only for you)", ""]
    out += [f"- `{f}`" for f in contract_files] if contract_files else ["- None yet."]
    out.append("")

    team = cfg.get("team", {}).get("members", [])
    if team:
        out += ["## Team", ""] + [f"- {m.get('name', '')} (@{m.get('github', '')}) — {m.get('role', '')} · tools: {m.get('ai_tool', '')}" for m in team] + [""]

    out += ["## Conventions", ""]
    if conventions:
        if len(conventions) > MAX_CONVENTIONS_CHARS:
            conventions = conventions[:MAX_CONVENTIONS_CHARS].rsplit("\n", 1)[0] + "\n\n… (truncated — full text in `.agentthon/artifacts/conventions.md`)"
        out.append(re.sub(r"^#\s.*\n", "", conventions, count=1).strip())
    else:
        out.append("Not written yet — see `.agentthon/artifacts/conventions.md` once the Architect has written it.")
    out += ["", "## More", "", "- Team practices: `TEAM.md`", "- Purpose, scope and demo script: `.agentthon/artifacts/brief.md`"]
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = os.path.abspath(sys.argv[1])
    content = body(root)
    stale = []
    for rel, title in OUTPUTS.items():
        text = f"{title}\n\n{MARK}\n\n{content}"
        path = os.path.join(root, rel)
        if "--check" in sys.argv:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
            print(f"wrote {rel}")
    if "--check" in sys.argv:
        if stale:
            print("Out of date: " + ", ".join(stale) + " — run: python3 .agentthon/bin/sync-instructions.py .")
            return 1
        print("instruction files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
