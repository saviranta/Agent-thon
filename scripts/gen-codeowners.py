#!/usr/bin/env python3
"""gen-codeowners.py — generate .github/CODEOWNERS from .agentthon/ownership.yml.

Usage: gen-codeowners.py <project-root> [--check]

Owner mapping:
  @handle            → that handle (+ area reviewers)
  agents             → area reviewers, else config.team.default_reviewers
  architect / shared → area reviewers, else config.team.default_reviewers
GitHub uses the LAST matching line, so areas are written from least to most specific.
--check: exit 1 if the file is missing or out of date (used by CI).
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ownership import _specificity, load_ownership  # noqa: E402

HEADER = "# Generated by Agent-thon from .agentthon/ownership.yml — do not edit by hand.\n# Regenerate: python3 .agentthon/bin/gen-codeowners.py .\n"


def handle(h):
    h = h.strip()
    return h if h.startswith("@") else f"@{h}"


def render(root):
    cfg = json.load(open(os.path.join(root, ".agentthon", "config.json")))
    defaults = [handle(h) for h in cfg.get("team", {}).get("default_reviewers", []) if h]
    lines = [HEADER]
    if defaults:
        lines.append(f"* {' '.join(defaults)}")
    for area in sorted(load_ownership(root), key=lambda a: _specificity(a["path"])):
        owners = []
        if area["owner"] and area["owner"].startswith("@"):
            owners.append(area["owner"])
        owners += [handle(r) for r in area.get("reviewers", []) if r]
        if not owners:
            owners = defaults
        owners = list(dict.fromkeys(owners))
        if not owners:
            lines.append(f"# {area['path']}  (owner: {area['owner']} — no reviewers configured)")
            continue
        pattern = area["path"]
        pattern = pattern if pattern.startswith("/") else "/" + pattern
        lines.append(f"{pattern} {' '.join(owners)}")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = os.path.abspath(sys.argv[1])
    out = os.path.join(root, ".github", "CODEOWNERS")
    content = render(root)
    if "--check" in sys.argv:
        current = open(out).read() if os.path.exists(out) else ""
        if current != content:
            print("CODEOWNERS is out of date — run: python3 .agentthon/bin/gen-codeowners.py .")
            return 1
        print("CODEOWNERS up to date")
        return 0
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write(content)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
